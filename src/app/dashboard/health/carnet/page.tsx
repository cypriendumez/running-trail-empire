/** AAAA-MM-JJ → JJ/MM/AAAA, sans fuseau : la date est déjà celle de l'athlète. */
const jjmm = (iso: string) => (iso.length >= 10 ? `${iso.slice(8, 10)}/${iso.slice(5, 7)}/${iso.slice(0, 4)}` : iso);
const decale = (jour: string, n: number) => { const d = new Date(`${jour}T12:00:00Z`); d.setUTCDate(d.getUTCDate() + n); return d.toISOString().slice(0, 10); };
const lundiDe = (jour: string) => { const d = new Date(`${jour}T12:00:00Z`); const j = (d.getUTCDay() + 6) % 7; d.setUTCDate(d.getUTCDate() - j); return d.toISOString().slice(0, 10); };
const duree = (sec: number) => { const m = Math.round(sec / 60); return m >= 60 ? `${Math.floor(m / 60)} h ${String(m % 60).padStart(2, "0")}` : `${m} min`; };

export default async function CarnetPage() {
  const supabase = await createClient();
  const { data: { user } } = await supabase.auth.getUser();
  if (!user) return null;
  const lang = await getAccountLang(supabase, user.id);
  const t = TXT[lang] ?? TXT.fr;
  const jour = aujourdhui(FUSEAU_DEFAUT);
  const debut60 = decale(jour, -60), debut56 = decale(lundiDe(jour), -49), debut28 = decale(jour, -28);

  const [declRes, ressRes, seancesRes, consRes] = await Promise.all([
    supabase.from("notifications").select("data,created_at").eq("user_id", user.id).eq("type", "pain_report")
      .gte("created_at", `${debut60}T00:00:00Z`).order("created_at", { ascending: false }).limit(200),
    supabase.from("notifications").select("data,created_at").eq("user_id", user.id).eq("type", "session_feedback")
      .gte("created_at", `${debut60}T00:00:00Z`).order("created_at", { ascending: false }).limit(200),
    supabase.from("workouts").select("date,sport,distance_km,duration_seconds,avg_hr").eq("user_id", user.id)
      .gte("date", debut56).order("date", { ascending: false }).limit(200),
    supabase.from("notifications").select("data").eq("user_id", user.id).eq("type", TYPE_CONSIGNES).order("created_at", { ascending: false }).limit(1),
  ]);
  // Une lecture ratée se DIT sur le carnet : un médecin lirait sinon « aucune douleur ».
  const enPanne = [declRes, ressRes, seancesRes, consRes].some((r) => r.error && estUnePanne(r));
  if (enPanne) console.error("[carnet] lecture illisible");

  type Ligne = { date: string; zone: string; niveau: string; etat: string; origine: string };
  const lignes: Ligne[] = [
    ...((declRes.data ?? []) as { data: Record<string, unknown> | null; created_at: string }[]).map((r) => ({
      date: String(r.data?.date ?? r.created_at).slice(0, 10),
      zone: String(r.data?.zone ?? ""),
      niveau: Number(r.data?.level) > 0 ? `${Number(r.data?.level)}/10` : "—",
      etat: t[`etat_${String(r.data?.etat ?? "actif")}`] ?? t.etat_actif,
      origine: t.schema,
    })),
    ...((ressRes.data ?? []) as { data: Record<string, unknown> | null; created_at: string }[]).flatMap((r) => {
      const passees = Array.isArray(r.data?.painPasse) ? (r.data!.painPasse as unknown[]).map(String) : [];
      return douleursDeclarees(r.data?.pain).map((z) => ({
        date: String(r.data?.date ?? r.created_at).slice(0, 10),
        zone: traduireDouleur(z, lang),
        niveau: typeof r.data?.rpe === "number" ? `${t.ressenti} ${r.data.rpe}/10` : "—",
        etat: passees.includes(z) ? t.etat_resolu : t.etat_actif,
        origine: t.seance,
      }));
    }),
  ].filter((l) => l.zone).sort((a, b) => b.date.localeCompare(a.date));

  const seances = ((seancesRes.data ?? []) as { date: string; sport: string | null; distance_km: number | null; duration_seconds: number | null; avg_hr: number | null }[])
    .filter((s) => isRun(s.sport ?? "run"));
  const semaines = Array.from({ length: 8 }, (_, i) => decale(lundiDe(jour), -7 * i)).map((lundi) => {
    const fin = decale(lundi, 7);
    const dans = seances.filter((s) => s.date >= lundi && s.date < fin);
    return { lundi, km: Math.round(dans.reduce((a, s) => a + (Number(s.distance_km) || 0), 0)), n: dans.length };
  });
  const recentes = seances.filter((s) => s.date >= debut28);
  const consignes = consignesEnVigueur(((consRes.data ?? []) as { data?: unknown }[])[0]?.data, jour);

  const th = "border-b border-zinc-200 px-2 py-1 text-left text-[11px] font-semibold uppercase tracking-wide text-zinc-500";
  const td = "border-b border-zinc-100 px-2 py-1 text-[12px] text-zinc-800";
  return (
    <div className="mx-auto max-w-3xl space-y-6 px-4 py-6 print:max-w-none print:p-0">
      {/* À l'impression, seule la page part : ni menu, ni en-tête de l'application. */}
      <style>{`@media print { aside, nav, header, [data-print-hide] { display: none !important; } body { background: #fff !important; } }`}</style>
      <div className="flex flex-wrap items-center justify-between gap-3 print:hidden">
        <Link href="/dashboard/health" className="text-sm font-semibold text-emerald-700 hover:underline">{t.retour}</Link>
        <BoutonImprimer libelle={t.imprimer} />
      </div>
      <div>
        <h1 className="text-xl font-bold text-zinc-900">{t.titre}</h1>
        <p className="mt-1 text-[12px] text-zinc-500">{t.sous}</p>
        <p className="mt-1 text-[11px] text-zinc-400">{t.genere} {jjmm(jour)}</p>
      </div>
      {enPanne && <p className="rounded-lg border border-rose-200 bg-rose-50 px-3 py-2 text-[12px] text-rose-800">{t.panne}</p>}

      <section>
        <h2 className="mb-2 text-sm font-semibold text-zinc-900">{t.douleurs}</h2>
        {lignes.length === 0 ? <p className="text-[12px] text-zinc-500">{t.aucune}</p> : (
          <table className="w-full border-collapse">
            <thead><tr><th className={th}>{t.date}</th><th className={th}>{t.zone}</th><th className={th}>{t.niveau}</th><th className={th}>{t.etat}</th><th className={th}>{t.origine}</th></tr></thead>
            <tbody>{lignes.map((l, i) => <tr key={i}><td className={td}>{jjmm(l.date)}</td><td className={td}>{l.zone}</td><td className={td}>{l.niveau}</td><td className={td}>{l.etat}</td><td className={td}>{l.origine}</td></tr>)}</tbody>
          </table>
        )}
      </section>

      <section>
        <h2 className="mb-2 text-sm font-semibold text-zinc-900">{t.charge}</h2>
        <table className="w-full border-collapse">
          <thead><tr><th className={th}>{t.semaine}</th><th className={th}>{t.km}</th><th className={th}>{t.sorties}</th></tr></thead>
          <tbody>{semaines.map((s) => <tr key={s.lundi}><td className={td}>{jjmm(s.lundi)}</td><td className={td}>{s.km}</td><td className={td}>{s.n}</td></tr>)}</tbody>
        </table>
      </section>

      <section>
        <h2 className="mb-2 text-sm font-semibold text-zinc-900">{t.seances}</h2>
        <table className="w-full border-collapse">
          <thead><tr><th className={th}>{t.date}</th><th className={th}>{t.distance}</th><th className={th}>{t.duree}</th><th className={th}>{t.fc}</th></tr></thead>
          <tbody>{recentes.map((s, i) => (
            <tr key={i}>
              <td className={td}>{jjmm(s.date)}</td>
              <td className={td}>{s.distance_km != null ? `${Number(s.distance_km).toFixed(1).replace(".", ",")} km` : "—"}</td>
              <td className={td}>{s.duration_seconds ? duree(s.duration_seconds) : "—"}</td>
              <td className={td}>{s.avg_hr ? `${s.avg_hr} bpm` : "—"}</td>
            </tr>
          ))}</tbody>
        </table>
      </section>

      <section>
        <h2 className="mb-2 text-sm font-semibold text-zinc-900">{t.consignes}</h2>
        {consignes ? (
          <ul className="list-disc space-y-0.5 pl-5 text-[12px] text-zinc-800">
            {consignes.dureeMaxMin != null && <li>{t.dureeMax} : {consignes.dureeMaxMin} min</li>}
            {consignes.seancesMaxSemaine != null && <li>{t.seancesMax} : {consignes.seancesMaxSemaine}</li>}
            {consignes.sansIntensite && <li>{t.sansIntensite}</li>}
            <li>{t.jusquAu} {jjmm(consignes.jusquAu)}</li>
          </ul>
        ) : <p className="text-[12px] text-zinc-500">{t.aucuneConsigne}</p>}
      </section>
    </div>
  );
}
