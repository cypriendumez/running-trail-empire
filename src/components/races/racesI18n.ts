// Libellé de plage de dates (clé dérivée de la valeur `days`).
export function dateRangeKey(days: number): string {
  if (days >= 100000) return "dr.all";
  if (days === -1) return "dr.tbd";
  return { 7: "dr.week", 30: "dr.month", 90: "dr.m3", 180: "dr.m6", 365: "dr.y1", 730: "dr.y2" }[days] ?? "dr.all";
}
